/**
 * Generates `src/rpc-catalog.generated.ts` from the locally recovered route
 * table in `reference/` (gitignored). Only the structured interface facts are
 * emitted — method name, HTTP verb, path, service, stream mode, limits — plus
 * our own safety classification. No upstream comments or code are copied.
 *
 * Run: bun run gen:catalog
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..", "..");
const routesPath = join(
  repoRoot,
  "reference/recovered-src/shared/hatch/gatewayHttpRoutes.ts",
);
const outPath = join(here, "..", "src", "rpc-catalog.generated.ts");

type UpstreamRoute = {
  method: string;
  httpMethod: string;
  path: string;
  service?: string;
  requestBody?: string;
  aliases?: string[];
  noiseOnly?: boolean;
  responseType?: string;
  maxResponseBytes?: number;
  requestTimeoutMs?: number;
  responseIdleTimeoutMs?: number;
  channel?: string;
  streamMode?: string;
  connectionClass?: string;
};

const mod = (await import(routesPath)) as {
  HATCH_GATEWAY_HTTP_ROUTES: UpstreamRoute[];
};
const routes = mod.HATCH_GATEWAY_HTTP_ROUTES;

const DESTRUCTIVE =
  /(^|\.)(delete|remove|reset|unlink|revoke|disconnect|unpair|unshare|archive|wipe|purge|clear|cancel|delete_turn|uninstall)(\.|$)/;
const SENSITIVE_PREFIX =
  /^(credentials|vault|email|subscription|payments?|ssh|grants|connectors|foa|foa_auth|channels|whatsapp_companion|messenger_companion|peers|support|dyi|bug_report_logs|home_link_bug_reports)\b/;
const SENSITIVE_SERVICE = new Set(["vault", "authd", "ssh_access", "sentinel"]);

function classify(
  r: UpstreamRoute,
): "read" | "write" | "destructive" | "sensitive" {
  const service = r.service ?? "daemon";
  if (SENSITIVE_SERVICE.has(service) || SENSITIVE_PREFIX.test(r.method)) {
    return "sensitive";
  }
  if (r.httpMethod === "DELETE" || DESTRUCTIVE.test(r.method)) {
    return "destructive";
  }
  if (r.httpMethod === "GET") return "read";
  if (r.streamMode === "subscription" && /\.subscribe$/.test(r.method)) {
    return "read";
  }
  return "write";
}

function compact(r: UpstreamRoute) {
  const out: Record<string, unknown> = {
    method: r.method,
    httpMethod: r.httpMethod,
    path: r.path,
    service: r.service ?? "daemon",
    safety: classify(r),
  };
  if (r.requestBody) out.requestBody = r.requestBody;
  if (r.aliases?.length) out.aliases = r.aliases;
  if (r.noiseOnly) out.noiseOnly = true;
  if (r.responseType) out.responseType = r.responseType;
  if (r.maxResponseBytes != null && Number.isFinite(r.maxResponseBytes)) {
    out.maxResponseBytes = r.maxResponseBytes;
  }
  if (r.maxResponseBytes === Number.POSITIVE_INFINITY) {
    out.unboundedResponse = true;
  }
  if (r.requestTimeoutMs != null) out.requestTimeoutMs = r.requestTimeoutMs;
  if (r.responseIdleTimeoutMs != null) {
    out.responseIdleTimeoutMs = r.responseIdleTimeoutMs;
  }
  if (r.channel) out.channel = r.channel;
  if (r.streamMode) out.streamMode = r.streamMode;
  if (r.connectionClass) out.connectionClass = r.connectionClass;
  return out;
}

const seen = new Set<string>();
const entries = [];
for (const r of routes) {
  if (seen.has(r.method)) continue;
  seen.add(r.method);
  entries.push(compact(r));
}
entries.sort((a, b) => String(a.method).localeCompare(String(b.method)));

const banner = `// GENERATED by scripts/generate-rpc-catalog.ts — do not edit by hand.
// Muse gateway RPC surface: ${entries.length} methods.
`;
const body = `import type { RpcRouteSpec } from "./rpc-catalog.js";

export const RPC_ROUTES: readonly RpcRouteSpec[] = ${JSON.stringify(entries, null, 2)} as const as readonly RpcRouteSpec[];
`;
writeFileSync(outPath, banner + body);
console.log(`wrote ${entries.length} routes -> ${outPath}`);
